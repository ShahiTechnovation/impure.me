import {chromium} from 'playwright';
import sharp from 'sharp';
import fs from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1200,height:900},reducedMotion:'no-preference'});
await page.goto('https://builderbaseflag.vercel.app/',{waitUntil:'networkidle'});
await page.waitForTimeout(1800);
const a=await page.locator('canvas').screenshot();
await page.waitForTimeout(1000);
const b=await page.locator('canvas').screenshot();
console.log('Flag frames differ:',!a.equals(b));
await sharp(a).webp({quality:85}).toFile('public/images/work/builder-base-flag.webp');
await fs.writeFile('artifacts/v23/sources/flag-frame-a.png',a);
await fs.writeFile('artifacts/v23/sources/flag-frame-b.png',b);
await page.setViewportSize({width:1440,height:960});
await page.goto('https://flow-mon.vercel.app/app',{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Load Monad demo flow'}).click();
await page.waitForTimeout(700);
await sharp(await page.screenshot()).webp({quality:86}).toFile('public/images/work/flowmon-v23.webp');
console.log('FlowMon demo captured; no flow executed.');
await browser.close();
